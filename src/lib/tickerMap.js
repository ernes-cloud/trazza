// ── MIC (ISO 10383 exchange codes) → Yahoo Finance suffix ────────────────────
// Brokers and users identify listings by MIC ("AMZ.XGAT" = Amazon on Tradegate),
// but Yahoo only understands its own suffixes — a MIC-suffixed ticker never loads
// a price. Yahoo has no Tradegate/Gettex feed, so those map to Xetra (.DE): same
// instrument, same EUR quote. Only KNOWN codes are translated; unknown 4-letter
// suffixes pass through untouched.
const MIC_TO_YAHOO_SUFFIX = {
  // US — Yahoo uses the bare symbol
  XNAS: '', XNYS: '', XNGS: '', XNMS: '', XNCM: '', XASE: '', ARCX: '', BATS: '', XCBO: '',
  // Germany
  XETR: '.DE', XETA: '.DE', XETB: '.DE',
  XGAT: '.DE', TGAT: '.DE', XGRM: '.DE', // Tradegate/Gettex → Xetra proxy
  XFRA: '.F', XSTU: '.SG', XMUN: '.MU', XBER: '.BE', XDUS: '.DU', XHAM: '.HM', XHAN: '.HA',
  // Rest of Europe
  XPAR: '.PA', XAMS: '.AS', XBRU: '.BR', XLIS: '.LS',
  XMIL: '.MI', MTAA: '.MI', ETLX: '.MI',
  XMAD: '.MC', MABX: '.MC', XMCE: '.MC',
  XLON: '.L', XSWX: '.SW', XVTX: '.SW', XWBO: '.VI', XDUB: '.IR', XMSM: '.IR',
  XSTO: '.ST', XCSE: '.CO', XOSL: '.OL', XHEL: '.HE', XWAR: '.WA',
  // Americas / Asia-Pacific
  XTSE: '.TO', XTSX: '.V', XMEX: '.MX', XBSP: '.SA',
  XASX: '.AX', XHKG: '.HK', XSES: '.SI', XTKS: '.T',
};

const splitKnownMicSuffix = (upperTicker) => {
  const match = /^(.+)\.([A-Z0-9]{4})$/.exec(upperTicker);
  if (!match) return null;
  const suffix = MIC_TO_YAHOO_SUFFIX[match[2]];
  return suffix === undefined ? null : { base: match[1], suffix };
};

export const resolveTicker = (tickerOrIsin) => {
  if (!tickerOrIsin) return tickerOrIsin;
  // Handle "Identifier [EXCH] (CURRENCY)" or "Identifier (CURRENCY)" format
  const clean = tickerOrIsin.replace(/\s*\[.*?\]/g, '').replace(/\s*\([A-Z]{3}\)$/i, '').trim();
  const upper = clean.toUpperCase();
  if (TICKER_MAP[upper]) return TICKER_MAP[upper];
  const mic = splitKnownMicSuffix(upper);
  // Prefer the base-symbol alias (AMZ → AMZ.DE) over blind suffix translation
  if (mic) return TICKER_MAP[mic.base] || `${mic.base}${mic.suffix}`;
  return clean;
};

/**
 * Like resolveTicker but returns null when the input is not in TICKER_MAP.
 * Used for resolution-priority logic: lets callers distinguish "explicitly mapped"
 * (e.g. 'AMZ' → 'AMZ.DE') from "identity fallback" (e.g. 'AMZN' → 'AMZN').
 * A MIC-suffixed ticker counts as explicit ONLY when its base symbol is in the map;
 * pure MIC translation stays non-strict so dynamic/shared maps keep priority.
 */
export const strictResolveTicker = (tickerOrIsin) => {
  if (!tickerOrIsin) return null;
  const clean = tickerOrIsin.replace(/\s*\[.*?\]/g, '').replace(/\s*\([A-Z]{3}\)$/i, '').trim();
  const upper = clean.toUpperCase();
  if (TICKER_MAP[upper]) return TICKER_MAP[upper];
  const mic = splitKnownMicSuffix(upper);
  return (mic && TICKER_MAP[mic.base]) || null;
};

/**
 * Infers the currency in which Yahoo Finance quotes a given ticker.
 * This is the PRICE currency (needed for FX conversion), NOT the trade settlement
 * currency (which can be EUR for Xetra trades of US stocks like AMZN).
 *
 * Rules follow Yahoo Finance conventions:
 *   .L  → AMBIGUOUS: most LSE listings are pence (→ GBP after /100) but many LSE
 *         ETFs are USD-denominated (VUAA.L, SMH.L). When the caller knows the
 *         asset's native currency (assets.currency from the import), pass it as
 *         assetCurrency to disambiguate; without it we default to GBP.
 *   .DE .AS .PA .MI .MC .ST .CO .OL .HE .AT .PR .LS .BR → EUR
 *   .TO .VN → CAD
 *   .HK → HKD  |  .AX → AUD  |  .SI → SGD
 *   BTC-USD / ETH-EUR format → last segment after '-'
 *   No suffix → NYSE / NASDAQ → USD
 */
export const inferTickerCurrency = (ticker, assetCurrency = null) => {
  if (!ticker) return 'EUR';
  if (ticker.endsWith('.L')) {
    const cur = (assetCurrency || '').toUpperCase();
    if (cur && cur !== 'GBP' && cur !== 'GBX') return cur;
    return 'GBP';
  }
  if (/\.(DE|AS|PA|MI|MC|ST|CO|OL|HE|AT|PR|LS|BR)$/i.test(ticker)) return 'EUR';
  if (/\.(TO|VN)$/i.test(ticker)) return 'CAD';
  if (ticker.endsWith('.HK')) return 'HKD';
  if (ticker.endsWith('.AX')) return 'AUD';
  if (ticker.endsWith('.SI')) return 'SGD';
  if (ticker.includes('-')) return ticker.split('-').pop() || 'USD';
  return 'USD';
};

export const getIsinByTicker = (ticker) => {
  if (!ticker) return null;
  const upper = ticker.toUpperCase();
  // Find which ISIN key in TICKER_MAP resolves to this ticker
  const entry = Object.entries(TICKER_MAP).find(([, mappedTicker]) => mappedTicker.toUpperCase() === upper);
  return entry ? entry[0] : null;
};
