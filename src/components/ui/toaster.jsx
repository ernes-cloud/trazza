import React from 'react';
import {
  Toast,
  ToastClose,
  ToastDescription,
  ToastProvider,
  ToastTitle,
  ToastViewport,
} from "@/components/ui/toast"
import { useToast } from "@/components/ui/use-toast"

export function Toaster() {
  const { toasts } = useToast()

  return (
    <ToastProvider>
      {/* `dismiss` se saca del spread A PROPÓSITO: use-toast lo mete en el objeto
          del toast y, colándose en ...props, Radix lo reenviaba al <li> del DOM —
          de ahí el warning "Invalid value for prop `dismiss` on <li> tag". */}
      {toasts.map(function ({ id, title, description, action, dismiss, ...props }) {
        return (
          <Toast key={id} {...props}>
            <div className="grid gap-1">
              {title && <ToastTitle>{title}</ToastTitle>}
              {description && (
                <ToastDescription>{description}</ToastDescription>
              )}
            </div>
            {action}
            <ToastClose />
          </Toast>
        )
      })}
      <ToastViewport />
    </ToastProvider>
  )
}